let currentLanguage = localStorage.getItem("btc_helper_lang") || "es";
if (!I18N_DICTIONARY[currentLanguage]) currentLanguage = "es";

function t(key) {
  return I18N_DICTIONARY[currentLanguage][key] || key;
}

function translateStatic() {
  document.documentElement.lang = currentLanguage;
  document.querySelectorAll("[data-i18n]").forEach((element) => {
    element.textContent = t(element.dataset.i18n);
  });
  document.querySelectorAll("[data-lang]").forEach((element) => {
    element.classList.toggle("active", element.dataset.lang === currentLanguage);
  });
}

function setLanguage(language) {
  if (!I18N_DICTIONARY[language]) return;
  currentLanguage = language;
  localStorage.setItem("btc_helper_lang", language);
  translateStatic();
  window.dispatchEvent(new CustomEvent("languagechange"));
}

window.I18N_DICTIONARY = I18N_DICTIONARY;
window.t = t;
window.setLanguage = setLanguage;
window.getLanguage = () => currentLanguage;
